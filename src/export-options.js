/** @typedef {import('./types.js').Heading} Heading */
/** @typedef {import('./types.js').Doc} Doc */
/**
 * #+TITLE / #+AUTHOR / #+DATE / #+OPTIONS -- shared, pure parsing for
 * every export format (HTML/ASCII/ODT) to build its own
 * title block and apply the same #+OPTIONS: toggles consistently,
 * rather than four separate, potentially-drifting implementations of
 * the same six keys.
 *
 * toc: and num: are genuinely INDEPENDENT in real org (confirmed
 * directly against real Emacs org-mode's own HTML export, not
 * assumed): num: controls whether headings themselves get section
 * numbers (1, 1.1, 2, ...) anywhere they're shown at all; toc:
 * controls whether a Table of Contents is generated, and to what
 * depth (an integer), independent of whatever num: is set to -- a
 * depth-limited ToC still lists every heading up to that depth even
 * with num:nil (just without number prefixes), and full section
 * numbering still applies throughout the body even with toc:nil (no
 * ToC generated at all). This app's own existing ASCII exporter
 * used to conflate the two into one combined toggle; this module
 * fixes that.
 */

import { parseBrokenLinks } from './broken-links.js';

/** @type {Record<string, any>} */
const DEFAULT_OPTIONS = { toc: true, num: true, sup: 't', author: true, date: true, creator: false, broken: 'nil' };

/** `key:value` in an #+OPTIONS: line: a value is a word or a Lisp list in parentheses (`d:(not "LOGBOOK")`), and the key may be punctuation (`\n:t`, `':t`, `::nil`). */
const OPTION_PAIR_RE = /([^\s:]+|:):(\((?:[^()]|\([^()]*\))*\)|\S*)/g;

/**
 * Every key of the #+OPTIONS: lines as written (the last one wins), for the exporters that read more of them than parseExportOptions
 * returns: `todo`, `pri`, `tags`, `stat`, `tasks`, `p`, `d`, `arch`, `\n`, `'`, `*`, `e`, `f`, `tex`, `title`, `email` ...
 * @param {Doc} doc
 * @returns {Record<string, string>}
 */
function rawExportOptions(doc) {
  /** @type {Record<string, string>} */
  const raw = {};
  for (const kw of doc.keywords || []) {
    if (kw.key.toUpperCase() !== 'OPTIONS') continue;
    for (const m of kw.value.matchAll(OPTION_PAIR_RE)) if (m[2] !== '') raw[m[1]] = m[2];
  }
  return raw;
}

/** Parses every #+OPTIONS: line in `doc.keywords` into a single,
 *  merged `{ toc, num, sup, author, date, creator }` object -- a
 *  later value for the same key overwrites an earlier one, whether
 *  from a repeated key on one line or a second #+OPTIONS: line
 *  entirely (real org's own actual "last wins" precedence, matching
 *  this app's own already-established handling of repeated file
 *  keywords elsewhere -- see startup-config.js).
 *
 *  toc: `true` (default, "t") | `false` ("nil") | a positive integer
 *  (a depth limit, e.g. `toc:2`) -- the ToC lists headings only up to
 *  that many levels deep; num: boolean, default true; sup: `'t'` |
 *  `'nil'` | `'{}'`, default `'t'` -- matches getUseSubSuperscripts's
 *  own three-state convention directly, this is real org's own
 *  ^: key (a literal caret, not a word); author/date: boolean,
 *  default true -- whether #+AUTHOR/#+DATE (when the document
 *  actually has one) appear in the export at all; creator: boolean,
 * @param {Doc} doc
 * @param {string} [sup] what org-use-sub-superscripts says, used when the file has no #+OPTIONS: ^:
 * @param {import('./broken-links.js').BrokenLinks} [broken] what org-export-with-broken-links says, used when the file has no #+OPTIONS: broken-links:
 *  default false -- whether a "Generated by ..." notice appears. */
function parseExportOptions(doc, sup = 't', broken = 'nil') {
  const options = { ...DEFAULT_OPTIONS };
  options.sup = sup;
  options.broken = broken;
  for (const kw of doc.keywords || []) {
    if (kw.key.toUpperCase() !== 'OPTIONS') continue;
    for (const m of kw.value.matchAll(OPTION_PAIR_RE)) {
      const [, key, value] = m;
      if (value === '') continue;
      if (key === 'toc') {
        if (value === 'nil') options.toc = false;
        else if (/^\d+$/.test(value)) options.toc = Number(value);
        else options.toc = true;
      } else if (key === 'num') {
        options.num = value !== 'nil';
      } else if (key === '^') {
        options.sup = value === 'nil' || value === '{}' ? value : 't';
      } else if (key === 'author') {
        options.author = value !== 'nil';
      } else if (key === 'date') {
        options.date = value !== 'nil';
      } else if (key === 'creator') {
        options.creator = value === 't';
      } else if (key === 'broken-links') {
        options.broken = parseBrokenLinks(value, options.broken);
      }
      // Every other real #+OPTIONS: key (tags:, todo:, pri:, e:, and
      // many more) is silently ignored -- out of scope for this
      // app's own narrower subset.
    }
  }
  return options;
}

/** The #+TITLE: of `doc`, trimmed; several lines are one title, joined by a blank (as in Org), or null when there is none. @param {Doc} doc */
function getDocTitle(doc) {
  /** @param {any} [k] */
  const all = (doc.keywords || []).filter((k) => k.key.toUpperCase() === 'TITLE');
  return all.length ? all.map((k) => k.value.trim()).join(' ') : null; // several lines are one, joined by a blank
}

/** @param {Doc} doc */
function getDocAuthor(doc) {
  /** @param {any} [k] */
  const all = (doc.keywords || []).filter((k) => k.key.toUpperCase() === 'AUTHOR');
  return all.length ? all.map((k) => k.value.trim()).join(' ') : null; // several lines are one, joined by a blank
}

/** @param {Doc} doc */
function getDocDate(doc) {
  /** @param {any} [k] */
  const all = (doc.keywords || []).filter((k) => k.key.toUpperCase() === 'DATE');
  return all.length ? all.map((k) => k.value.trim()).join(' ') : null; // several lines are one, joined by a blank
}

/** Every #+HTML_HEAD: line's own value, joined by newlines in source
 *  order -- multiple lines concatenate rather than only the last one
 *  winning (confirmed directly against real Emacs org-mode), since
 *  this is how a multi-line <style> block like the one in this app's
 *  own README example is actually written. Returns null when there
 *  are none at all, so a caller can tell "nothing to insert" apart
 *  from "an empty string was explicitly written." HTML export only --
 * @param {Doc} doc
 *  real org itself never reads this keyword for any other backend. */
function getHtmlHead(doc) {
  const lines = (doc.keywords || []).filter((k) => k.key.toUpperCase() === 'HTML_HEAD').map((k) => k.value);
  return lines.length > 0 ? lines.join('\n') : null;
}

export { rawExportOptions, parseExportOptions, getDocTitle, getDocAuthor, getDocDate, getHtmlHead };
