import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { parseOrg } from '../src/org-parser.js';
import { exportToAscii } from '../src/export-ascii.js';
import { exportToHtml } from '../src/export-html.js';
import { exportToLatex } from '../src/export-latex.js';
import { withExportVariables } from '../src/export-variables.js';
import { htmlContent, latexBody, straightQuotes } from './support/export-canon.js';
import { setTagsColumn } from '../src/tags-column.js';

setTagsColumn(0); // Emacs ran at org-tags-column 0

// test/fixtures/export-variables-oracle.json is what Emacs 29.3 (Org 9.6.15) exports for one document under each setting of the export
// variables; tools/gen-export-variables-oracle.mjs makes it. The settings reach the exporters through withExportVariables.
const { sample, sampleMacros, cases } = JSON.parse(fs.readFileSync(new URL('./fixtures/export-variables-oracle.json', import.meta.url), 'utf8'));
const KNOWN = JSON.parse(fs.readFileSync(new URL('./support/export-variables-known.json', import.meta.url), 'utf8'));

// the creator notice names the program (Emacs there, the app here), and a right-justified one is as wide as that name
const norm = (s) => straightQuotes(s).replace(/^[ \t]*(?:Emacs 29\.3 \(Org mode 9\.6\.15\)|Generated by org-pwa|Org Mode PWA)$/gm, '<creator>').trimEnd();

for (const c of cases) {
  for (const [backend, run, cut] of [
    ['ascii', (doc) => exportToAscii(doc, null, 72, {}), (s) => s],
    ['html', (doc) => exportToHtml(doc, null, {}), htmlContent],
    ['latex', (doc) => exportToLatex(doc, null, {}), latexBody],
  ]) {
    const id = `${c.name} / ${backend}`;
    test(`export variables: ${id} matches Emacs`, { todo: KNOWN[id] ?? false }, () => {
      const { doc } = withExportVariables(parseOrg(c.macros ? sampleMacros : sample), null, c.vars, { backend });
      assert.equal(norm(cut(run(doc))), norm(cut(c[backend])));
    });
  }
}

test('a #+OPTIONS: line of the file wins over the variables', () => {
  const org = '#+OPTIONS: toc:t num:nil\n\nIntro.\n\n* One\ntext\n';
  const plain = exportToAscii(parseOrg(org), null, 72, {});
  const { doc } = withExportVariables(parseOrg(org), null, { 'org-export-with-toc': 'nil', 'org-export-with-section-numbers': 't' });
  assert.equal(exportToAscii(doc, null, 72, {}), plain);
  const { doc: variableOnly } = withExportVariables(parseOrg('Intro.\n\n* One\ntext\n'), null, { 'org-export-with-toc': 'nil' });
  assert.ok(!/Table of Contents/.test(exportToAscii(variableOnly, null, 72, {})));
});

test('without a variable set the document is returned as it is', () => {
  const doc = parseOrg('* One\n');
  assert.equal(withExportVariables(doc, null, {}).doc, doc);
  assert.equal(withExportVariables(doc, null, { 'org-export-with-toc': 'garbage text (' }).doc, doc);
});

// What Emacs 29.3 (ox-org) writes for this text without and with #+OPTIONS: c:t d:t
test('Org export keeps CLOCK lines only with c:t, as Emacs does', async () => {
  const { exportOrgText } = await import('../src/export-org.js');
  const body = '* A\n:LOGBOOK:\nCLOCK: [2024-05-01 Wed 09:00]--[2024-05-01 Wed 10:30] =>  1:30\n:END:\nCLOCK: [2024-05-02 Thu 09:00]\ntext\n';
  const out = async (/** @type {string} */ text) => (await exportOrgText(parseOrg(text), async () => null, parseOrg, { minlevel: 1 })).split('\n').filter((l) => !l.startsWith('#')).join('\n').trim();
  assert.equal(await out(body), '* A\ntext');
  assert.equal(await out('#+OPTIONS: c:t d:t\n' + body), body.trim());
});
