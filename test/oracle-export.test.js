// Holds the ASCII (ascii and utf-8), HTML, LaTeX and Org exporters to Emacs 29.3 on the small documents of tools/oracle-export-cases.mjs
// (test/fixtures/oracle-export.json, made by tools/gen-oracle-export.mjs). HTML is compared from the content container to the postamble
// and LaTeX from \begin{document} to \end{document} (head and styles are covered by the other export tests); Org's reference hashes and the
// app's readable anchors are both renumbered by first use (test/support/export-canon.js). A case listed in KNOWN_DEVIATIONS differs
// from Emacs for the reason given; the test fails when such a case starts to match. A document for which Emacs signals an error
// (an undefined macro, a missing include or footnote definition) is not compared: the app exports what it can.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { parseOrg } from '../src/org-parser.js';
import { exportToAscii } from '../src/export-ascii.js';
import { exportToHtml } from '../src/export-html.js';
import { exportToLatex } from '../src/export-latex.js';
import { exportOrgText } from '../src/export-org.js';
import { htmlContent, latexBody, straightQuotes } from './support/export-canon.js';
import { KNOWN_DEVIATIONS } from './support/oracle-export-known.js';

const oracle = JSON.parse(fs.readFileSync(new URL('./fixtures/oracle-export.json', import.meta.url), 'utf8'));
/** @typedef {{ name: string, org: string, [backend: string]: string }} Case */

/** @type {Record<string, (org: string) => Promise<string> | string>} */
const RUN = {
  ascii: (org) => exportToAscii(parseOrg(org), null, 72, { charset: 'ascii' }),
  utf8: (org) => exportToAscii(parseOrg(org), null, 72, { charset: 'utf-8' }),
  html: (org) => htmlContent(exportToHtml(parseOrg(org))),
  latex: (org) => latexBody(exportToLatex(parseOrg(org))),
  orgx: (org) => exportOrgText(parseOrg(org), async () => null, parseOrg, { minlevel: 1 }),
};
/** What Emacs's text becomes before the comparison. @type {Record<string, (s: string) => string>} */
const WANT = {
  ascii: (s) => s,
  utf8: (s) => s,
  html: htmlContent,
  latex: latexBody,
  orgx: (s) => s.replace(/^# Created .*\n/, '').replace(/^#\+title: *\n/m, '').replace(/^#\+author: root\n?/m, '').replace(/^#\+creator: Emacs [\d.]+ \(Org mode [\d.]+\)$/m, '#+creator: Org Mode PWA'),
};
// the creator notice names the program (Emacs there, the app here), and a right-justified one is as wide as that name
const norm = (/** @type {string} */ s) => straightQuotes(s).replace(/^[ \t]*(?:Emacs 29\.3 \(Org mode 9\.6\.15\)|Generated by org-pwa|Org Mode PWA)$/gm, '<creator>').trimEnd();

/** The app's text for a case, or "ERROR message" when the exporter refuses the document. @param {string} backend @param {string} org */
async function ours(backend, org) {
  try {
    return String(await RUN[backend](org));
  } catch (e) {
    return 'ERROR ' + (e instanceof Error ? e.message : String(e));
  }
}
const known = (/** @type {string} */ backend, /** @type {string} */ name) => KNOWN_DEVIATIONS.find((k) => k.matches({ backend, name }));

for (const backend of Object.keys(RUN)) {
  test(`${backend} export gives what Emacs gives, case by case`, async () => {
    const wrong = [];
    const nowMatching = [];
    for (const c of /** @type {Case[]} */ (oracle.cases)) {
      const want = c[backend];
      if (want.startsWith('ERROR')) continue; // Emacs stops with an error; the app exports what it can (not compared)
      const got = await ours(backend, c.org);
      const ok = !got.startsWith('ERROR') && norm(got) === norm(WANT[backend](want));
      const k = known(backend, c.name);
      if (k && ok) nowMatching.push(`${c.name} (${k.id})`);
      else if (!k && !ok) wrong.push({ name: c.name, org: c.org, want: want.slice(0, 600), got: got.slice(0, 600) });
    }
    assert.deepEqual(nowMatching, [], 'listed as different but now equal: remove from KNOWN_DEVIATIONS');
    assert.equal(wrong.length, 0, `${wrong.length} of ${oracle.cases.length} differ from Emacs:\n` + JSON.stringify(wrong.slice(0, 3), null, 1));
  });
}
