// Holds the exporters to Emacs 29.3 on tools/gen-oracle-export-fixes.mjs (test/fixtures/oracle-export-fixes.json): select/exclude tags,
// footnote definitions and separators, inline tasks, timestamps, export options, subtree properties and #+INCLUDE of Org files. Includes
// are expanded first (as the export dialogs do); a case with `subtree` exports the first heading's subtree (not for Org). A case listed in
// oracle-export-fixes-known.js differs for the reason given, and the test fails when it starts to match.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { parseOrg } from '../src/org-parser.js';
import { exportToAscii } from '../src/export-ascii.js';
import { exportToHtml } from '../src/export-html.js';
import { exportToLatex } from '../src/export-latex.js';
import { exportOrgText } from '../src/export-org.js';
import { expandIncludes } from '../src/export-include.js';
import { setInlineTaskLevel } from '../src/inline-tasks.js';
import { setTagsColumn } from '../src/tags-column.js';
import { htmlContent, latexBody, straightQuotes } from './support/export-canon.js';
import { FIXES_KNOWN } from './support/oracle-export-fixes-known.js';

setTagsColumn(0);
setInlineTaskLevel(15); // org-inlinetask is loaded in the oracle
const oracle = JSON.parse(fs.readFileSync(new URL('./fixtures/oracle-export-fixes.json', import.meta.url), 'utf8'));

/** @param {{ org: string, files?: Record<string, string> }} c */
async function prepared(c) {
  const files = c.files || {};
  return expandIncludes(parseOrg(c.org), async (/** @type {string} */ p) => (files[p] !== undefined ? { content: files[p] } : null), parseOrg);
}
/** @param {import('../src/org-parser.js').Doc} doc @param {boolean | undefined} subtree */
const scopeOf = (doc, subtree) => (subtree ? doc.children[0] : null);
/** @type {Record<string, (c: any) => Promise<string>>} */
const RUN = {
  ascii: async (c) => { const d = await prepared(c); return exportToAscii(d, scopeOf(d, c.subtree), 72, { charset: 'ascii' }); },
  utf8: async (c) => { const d = await prepared(c); return exportToAscii(d, scopeOf(d, c.subtree), 72, { charset: 'utf-8' }); },
  html: async (c) => { const d = await prepared(c); return htmlContent(exportToHtml(d, scopeOf(d, c.subtree))); },
  latex: async (c) => { const d = await prepared(c); return latexBody(exportToLatex(d, scopeOf(d, c.subtree))); },
  orgx: (c) => exportOrgText(parseOrg(c.org), async (/** @type {string} */ p) => (c.files?.[p] !== undefined ? { content: c.files[p] } : null), parseOrg, { minlevel: 1 }),
};
/** @type {Record<string, (s: string) => string>} */
const WANT = {
  ascii: (s) => s,
  utf8: (s) => s,
  html: htmlContent,
  latex: latexBody,
  orgx: (s) => s.replace(/^# Created .*\n/, '').replace(/^#\+title: *\n/m, '').replace(/^#\+author: root\n?/m, '').replace(/^#\+creator: Emacs [\d.]+ \(Org mode [\d.]+\)$/m, '#+creator: Org Mode PWA'),
};
const norm = (/** @type {string} */ s) => straightQuotes(s).replace(/^[ \t]*(?:Emacs 29\.3 \(Org mode 9\.6\.15\)|Generated by org-pwa|Org Mode PWA)$/gm, '<creator>').trimEnd();

for (const backend of Object.keys(RUN)) {
  test(`export fixes: ${backend} gives what Emacs gives`, async () => {
    const wrong = [];
    const nowMatching = [];
    for (const c of oracle.cases) {
      const want = c[backend];
      if (want.startsWith('ERROR') || want === 'SKIP') continue;
      let got;
      try {
        got = String(await RUN[backend](c));
      } catch (e) {
        got = 'ERROR ' + (e instanceof Error ? e.message : String(e));
      }
      const ok = norm(got) === norm(WANT[backend](want));
      const k = FIXES_KNOWN.find((r) => r.matches({ backend, name: c.name }));
      if (k && ok) nowMatching.push(`${c.name} (${k.id})`);
      else if (!k && !ok) wrong.push({ name: c.name, want: WANT[backend](want).slice(-Number(process.env.SL || 500)), got: got.slice(-Number(process.env.SL || 500)) });
    }
    assert.deepEqual(nowMatching, [], 'listed as different but now equal: remove from the known list');
    assert.equal(wrong.length, 0, `${wrong.length} of ${oracle.cases.length} differ from Emacs:\n` + JSON.stringify(wrong, null, 1));
  });
}
