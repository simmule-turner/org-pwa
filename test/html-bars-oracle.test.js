// The preamble and postamble that real Emacs writes (fixtures from tools/gen-html-bars-oracle.mjs) against src/export-html.js.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { parseOrg } from '../src/org-parser.js';
import { exportToHtml } from '../src/export-html.js';

const cases = JSON.parse(fs.readFileSync(new URL('./fixtures/html-bars-oracle.json', import.meta.url), 'utf8'));
// the creator is org-pwa's own text, where Emacs names itself and Org
const EMACS_CREATOR = '<a href="https://www.gnu.org/software/emacs/">Emacs</a> 29.3 (<a href="https://orgmode.org">Org</a> mode 9.6.15)';
// the moment of export differs between runs
const STAMP = /\d{4}-\d\d-\d\d [A-Z][a-z]{2} \d\d:\d\d/g;
const grab = (html, id) => {
  const m = new RegExp(`<div id="${id}" class="status">\\n([\\s\\S]*?)\\n</div>`).exec(html);
  return m ? m[1].replace(STAMP, '<STAMP>') : null;
};

for (const c of cases) {
  const opt = c.src.split('\n').find((l) => l.startsWith('#+OPTIONS')).slice(10);
  test(`html bars: ${opt} (${c.src.split('\n')[0]})`, () => {
    const html = exportToHtml(parseOrg(c.src), null, { defaults: { ...(c.formats ? { preambleFormats: c.formats } : {}), ...(c.fn ? { preamble: { fn: c.fn } } : {}), ...(c.validationLink ? { validationLink: c.validationLink } : {}), ...(c.defaults || {}) } });
    assert.equal(grab(html, 'preamble'), c.preamble && c.preamble.replace(STAMP, '<STAMP>'), 'preamble');
    // Emacs fills a missing #+AUTHOR with the machine's user name, which the app cannot know; only user-full-name stands in for it here
    const machineAuthor = !c.src.includes('#+AUTHOR') && !(c.defaults && c.defaults.userFullName) && !/html-postamble:(nil|")/.test(opt);
    if (!machineAuthor) assert.equal(grab(html, 'postamble'), c.postamble && c.postamble.split(EMACS_CREATOR).join('Generated by org-pwa').replace(STAMP, '<STAMP>'), 'postamble');
  });
}
