// Writes src/export-dictionary.js from Emacs's `org-export-dictionary`: node tools/gen-export-dictionary.mjs
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const lisp = `(require 'json) (require 'ox) (princ "{")
(let ((first t)) (dolist (e org-export-dictionary)
  (unless first (princ ",")) (setq first nil)
  (princ (json-encode (car e))) (princ ":{")
  (let ((f2 t)) (dolist (l (cdr e)) (unless f2 (princ ",")) (setq f2 nil)
    (princ (json-encode (car l))) (princ ":{")
    (let ((p (cdr l)) (f3 t)) (while p (unless f3 (princ ",")) (setq f3 nil)
      (princ (json-encode (substring (symbol-name (car p)) 1))) (princ ":") (princ (json-encode (cadr p))) (setq p (cddr p))))
    (princ "}")))
  (princ "}")))
(princ "}")`;
const file = join(mkdtempSync(join(tmpdir(), 'dict-')), 'dict.el');
writeFileSync(file, lisp);
const out = execFileSync('emacs', ['--batch', '-Q', '-l', file], { encoding: 'utf8', maxBuffer: 1 << 26 });
const dict = JSON.parse(out);
const body = Object.entries(dict).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
writeFileSync(new URL('../src/export-dictionary.js', import.meta.url), `// @ts-check
// Generated by tools/gen-export-dictionary.mjs from Emacs's org-export-dictionary: the words an export writes for itself, by language.
/** @type {Record<string, Record<string, Record<string, string>>>} */
export const DICTIONARY = {
${body}
};

/**
 * The word or phrase \`key\` in \`language\` for the kind of output (\`html\`, \`ascii\`, \`latin1\`, \`utf-8\`, \`latex\`), as org-export-translate gives it:
 * the entry for that kind, else the language's default, else the key itself.
 * @param {string} key @param {string} language @param {string} kind
 */
export function translate(key, language, kind) {
  const entry = DICTIONARY[key]?.[language];
  return (entry && (entry[kind] ?? entry.default)) ?? key;
}
`);
