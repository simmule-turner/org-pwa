#!/usr/bin/env node
// Writes src/entities-latex.js: how Emacs's org-entities spells each entity in LaTeX (Org 9.6, org-entities).
// Run it after upgrading Emacs: node tools/gen-latex-entities.mjs
import fs from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const lisp = `(progn (require 'org-entities)
  (dolist (e org-entities)
    (when (listp e)
      (princ (format "%S\\n" (list (nth 0 e) (nth 1 e) (if (nth 2 e) t nil)))))))`;
const r = spawnSync('emacs', ['-Q', '--batch', '--eval', lisp], { encoding: 'utf8', maxBuffer: 1 << 24 });
if (r.status !== 0) throw new Error(r.stderr);
const lines = r.stdout.split('\n').filter((l) => l.startsWith('('));
const entries = lines.map((l) => {
  // ("alpha" "\\alpha" t) as Lisp: strings with \\ and \" escapes
  const m = /^\("((?:[^"\\]|\\.)*)" "((?:[^"\\]|\\.)*)" (t|nil)\)$/.exec(l);
  if (!m) throw new Error('cannot read ' + l);
  const unescape = (s) => s.replace(/\\(.)/g, '$1');
  return [unescape(m[1]), unescape(m[2]), m[3] === 't'];
});
const seen = new Set();
const unique = entries.filter(([name]) => !seen.has(name) && seen.add(name)); // org-entity-get takes the first of a name
const body = unique.map(([name, latex, math]) => `  ${JSON.stringify(name)}: [${JSON.stringify(latex)}, ${math}],`).join('\n');
fs.writeFileSync(
  root + 'src/entities-latex.js',
  `// @ts-check\n// Generated by tools/gen-latex-entities.mjs from Emacs's org-entities. Do not edit.\n// name -> [LaTeX text, true when it is math (written \\( ... \\))]\n/** @type {Record<string, [string, boolean]>} */\nexport const LATEX_ENTITIES = {\n${body}\n};\n`,
);
console.log(`wrote src/entities-latex.js (${unique.length} entities)`);
