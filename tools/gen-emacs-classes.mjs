#!/usr/bin/env node
/**
 * Writes src/emacs-classes.js: the characters of each regexp character class (`[[:alpha:]]`, ...), of each syntax class (`\sw`, `\s_`, ...)
 * and of the character categories (`\ca`, `\cj`, ...) exactly as Emacs 29.3 has them, for the Lisp interpreter's regexp translator.
 *   node tools/gen-emacs-classes.mjs   (needs emacs on the PATH)
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const el = `
(setq max-lisp-eval-depth 10000)
(require 'json)
(with-temp-buffer
(let* ((classes '("alpha" "alnum" "upper" "lower" "punct" "space" "blank" "graph" "print"))
       (cats (number-sequence 33 126))
       (res nil) (case-fold-search nil))
  (cl-flet ((ranges (pred)
              (let (out start)
                (dotimes (i #x110000)
                  (if (and (or (< i #xD800) (> i #xDFFF)) (funcall pred i))
                      (unless start (setq start i))
                    (when start (push (vector start (1- i)) out) (setq start nil))))
                (when start (push (vector start #x10FFFF) out))
                (vconcat (nreverse out)))))
    (dolist (c classes)
      (let ((re (concat "[[:" c ":]]")))
        (push (cons (intern c) (ranges (lambda (i) (string-match re (string i))))) res)))
    (dolist (k (string-to-list "w_.()\\"'"))
      (push (cons (intern (concat "syntax:" (string k))) (ranges (lambda (i) (eq (char-syntax i) k)))) res))
    (dolist (k cats)
      (let ((re (concat "\\\\c" (string k))))
        (when (condition-case nil (progn (string-match re "") t) (error nil))
          (let ((r (ranges (lambda (i) (string-match re (string i))))))
            (when (> (length r) 0)
              (push (cons (intern (concat "cat:" (string k))) r) res)))))))
  (setq res (nreverse res))
  (let ((json (json-encode res)))
    (with-temp-file (getenv "ORACLE_OUT") (insert json)))))
`;
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ecl-'));
fs.writeFileSync(path.join(dir, 'run.el'), el);
const r = spawnSync('emacs', ['--batch', '-Q', '-l', 'cl-lib', '-l', path.join(dir, 'run.el')], { env: { ...process.env, ORACLE_OUT: path.join(dir, 'out.json') }, encoding: 'utf8', input: '' });
if (r.status !== 0) { console.error(r.stderr); process.exit(1); }
const data = JSON.parse(fs.readFileSync(path.join(dir, 'out.json'), 'utf8'));
/** Each class as "start,length" pairs in base 36, the start relative to the end of the previous range. */
const body = (rs) => { let prev = 0; return rs.map(([a, b]) => { const t = `${(a - prev).toString(36)}.${(b - a).toString(36)}`; prev = b; return t; }).join(' '); };
let src = `// @ts-check
// Generated by tools/gen-emacs-classes.mjs from Emacs 29.3: do not edit.
// Each regexp class, syntax class and character category of Emacs as ranges, in a compact form: "gap.length" pairs in base 36, the gap
// counted from the end of the previous range; \`classBody\` turns one into the inside of a JavaScript character class (flag u).

/** @type {Readonly<Record<string, string>>} */
const RANGES = {
`;
for (const [k, v] of Object.entries(data)) src += `  ${JSON.stringify(k)}: '${body(v)}',\n`;
src += `};

/** @type {Map<string, string>} */
const decoded = new Map();

/** The inside of a JavaScript character class (flag u) for the class or category \`name\` (\`alpha\`, \`syntax:w\`, \`cat:a\`, ...), or undefined. @param {string} name */
export function classBody(name) {
  const hit = decoded.get(name);
  if (hit !== undefined) return hit;
  const packed = RANGES[name];
  if (packed === undefined) return undefined;
  let prev = 0;
  let out = '';
  for (const pair of packed.split(' ')) {
    const [gap, len] = pair.split('.');
    const a = prev + parseInt(gap, 36);
    const b = a + parseInt(len, 36);
    out += a === b ? \`\\\\u{\${a.toString(16)}}\` : \`\\\\u{\${a.toString(16)}}-\\\\u{\${b.toString(16)}}\`;
    prev = b;
  }
  decoded.set(name, out);
  return out;
}
`;
fs.writeFileSync(new URL('../src/emacs-classes.js', import.meta.url), src);
console.log('Wrote src/emacs-classes.js', Object.keys(data).length, 'classes,', src.length, 'bytes');
