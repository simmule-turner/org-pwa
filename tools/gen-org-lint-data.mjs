#!/usr/bin/env node
/**
 * Writes src/org-lint-data.js: the tables org-lint.el reads from Emacs 29.3 / Org 9.6.15 (link types, option names, Babel header
 * arguments, special properties), dumped by Emacs itself so the lint module needs no hand-copied lists.
 *   node tools/gen-org-lint-data.mjs   (needs emacs on the PATH)
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const el = `
(require 'org) (require 'org-lint) (require 'json) (require 'cl-lib)
(dolist (f (directory-files (file-name-directory (locate-library "org")) t "\\\\\`ob-[A-Za-z]+\\\\.elc?\\\\'"))
  (ignore-errors (require (intern (file-name-sans-extension (file-name-nondirectory f))))))
(defun enc (v)
  (cond ((eq v :any) ":any") ((null v) :null) ((symbolp v) (symbol-name v)) ((numberp v) v) ((stringp v) v)
        (t (format "%S" v))))
(defun enc-allowed (a)
  (cond ((eq a :any) ":any")
        (t (vconcat (mapcar (lambda (g) (vconcat (mapcar #'enc g))) a)))))
(defun enc-alist (al)
  (vconcat (mapcar (lambda (e) (list (cons 'name (symbol-name (car e))) (cons 'allowed (enc-allowed (cdr e))))) al)))
(let (langs)
  (dolist (s (apropos-internal "\\\\\`org-babel-header-args:" #'boundp))
    (push (cons (substring (symbol-name s) (length "org-babel-header-args:")) (enc-alist (symbol-value s))) langs))
  (with-temp-buffer
    (org-mode)
    (org-export--get-inbuffer-options)
    (princ (json-encode
      (list (cons 'linkTypes (vconcat (org-link-types)))
            (cons 'linkBracketRe org-link-bracket-re)
            (cons 'linkPlainRe org-link-plain-re)
            (cons 'linkAngleRe org-link-angle-re)
            (cons 'linkTypesRe org-link-types-re)
            (cons 'options (vconcat (delq nil (append (mapcar (lambda (o) (nth 2 o)) org-export-options-alist)
                                  (cl-mapcan (lambda (b) (mapcar (lambda (o) (nth 2 o)) (org-export-backend-options b))) org-export-registered-backends)))))
            (cons 'headerArgNames (vconcat (mapcar #'symbol-name org-babel-header-arg-names)))
            (cons 'commonHeaderArgs (enc-alist org-babel-common-header-args-w-values))
            (cons 'languageHeaderArgs langs)
            (cons 'specialProperties (vconcat org-special-properties)))))))
`;
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lintdata-'));
const file = path.join(dir, 'run.el');
fs.writeFileSync(file, el);
const r = spawnSync('emacs', ['--batch', '-Q', '-l', file], { encoding: 'utf8', maxBuffer: 1 << 28 });
const m = r.stdout.match(/\{.*\}$/s);
if (!m) { console.error(r.stderr.slice(-3000)); process.exit(1); }
const data = JSON.parse(m[0]);
const lines = Object.entries(data).map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};`);
fs.writeFileSync(new URL('../src/org-lint-data.js', import.meta.url), `// @ts-check\n// Generated by tools/gen-org-lint-data.mjs from Emacs 29.3 / Org 9.6.15: the tables org-lint.el reads. Do not edit.\n${lines.join('\n')}\n`);
console.log(Object.keys(data).join(' '));
