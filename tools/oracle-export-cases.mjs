/** @param {string} name @param {string} body text after the header */
const add = (name, body) => CASES.push({ name, org: HDR + body.replace(/^\n/, '') + (body.endsWith('\n') ? '' : '\n') });
/** A case that sets one #+OPTIONS key on top of the header (a later line wins, as in Emacs). */
const opt = (name, options, body) => add(name, `#+OPTIONS: ${options}\n${body}`);

