#!/usr/bin/env node
/**
 * Writes src/emacs-chars.js: which characters Emacs 29.3 counts as [[:space:]] and [[:alnum:]] (inline markup borders, sub/superscript
 * text) and which have the syntax classes the `$...$` closing check looks at, in an Org buffer.
 *   node tools/gen-emacs-chars.mjs   (needs emacs on the PATH)
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const el = `
(require 'org) (require 'json)
(with-temp-buffer (org-mode)
  (let (sp al (syn (make-hash-table)))
    (dotimes (c #x110000)
      (unless (and (>= c #xD800) (<= c #xDFFF))
        (let ((s (string c)))
          (when (string-match-p "[[:space:]]" s) (push c sp))
          (when (string-match-p "[[:alnum:]]" s) (push c al))
          (let ((k (char-syntax c)))
            (when (memq k '(?. ?\\s ?\\( ?\\) ?\\")) (push c (gethash k syn)))))))
    (with-temp-file (getenv "ORACLE_OUT")
      (insert (json-encode (list (cons 'space (vconcat (nreverse sp))) (cons 'alnum (vconcat (nreverse al)))
        (cons 'dollarFollow (vconcat (sort (append (gethash ?. syn) (gethash ?\\s syn) (gethash ?\\( syn) (gethash ?\\) syn) (gethash ?\\" syn) (list ?')) #'<)))))))))
`;
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ec-'));
fs.writeFileSync(path.join(dir, 'run.el'), el);
const r = spawnSync('emacs', ['--batch', '-Q', '-l', path.join(dir, 'run.el')], { env: { ...process.env, ORACLE_OUT: path.join(dir, 'out.json') }, encoding: 'utf8', input: '' });
if (r.status !== 0) { console.error(r.stderr); process.exit(1); }
const data = JSON.parse(fs.readFileSync(path.join(dir, 'out.json'), 'utf8'));
const ranges = (list) => { const out = []; for (const c of list) { const last = out[out.length - 1]; if (last && c === last[1] + 1) last[1] = c; else out.push([c, c]); } return out; };
const regexSource = (list) => ranges(list).map(([a, b]) => { const h = (n) => '\\u{' + n.toString(16) + '}'; return a === b ? h(a) : h(a) + '-' + h(b); }).join('');
const src = `// @ts-check
// Generated by tools/gen-emacs-chars.mjs from Emacs 29.3: do not edit.
// The characters Emacs counts as whitespace ([[:space:]]) and as letters or digits ([[:alnum:]]) in an Org buffer, and the ones with the
// syntax class of punctuation, whitespace, parenthesis or string quote that may follow a closing $ of a LaTeX fragment (or a quote mark).

/** Whitespace as Emacs reads it. */
export const EMACS_SPACE_RE = /[${regexSource(data.space)}]/u;
/** A letter or digit as Emacs reads it. */
export const EMACS_ALNUM_RE = /[${regexSource(data.alnum)}]/u;
/** What may follow the closing $ of a $...$ fragment (besides the end of the line). */
export const DOLLAR_FOLLOW_RE = /[${regexSource(data.dollarFollow)}]/u;
`;
fs.writeFileSync('src/emacs-chars.js', src);
console.log(src.length, 'bytes');
